import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = path.join(root, 'apps/mobile/sources/buzz');
const React = {
  Fragment: 'fragment',
  createElement: (type, props, ...children) => ({ type, props: { ...props, ...(children.length ? { children: children.length === 1 ? children[0] : children } : {}) } }),
  isValidElement: node => Boolean(node && typeof node === 'object' && 'type' in node),
  cloneElement: (node, patch, children) => ({ ...node, props: { ...node.props, ...patch, children } }),
  Children: { map: (children, fn) => [children].flat(Infinity).map(fn) },
};
const modules = new Map();
function load(relative) {
  if (modules.has(relative)) return modules.get(relative);
  const source = fs.readFileSync(path.join(base, relative), 'utf8');
  const exports = {};
  modules.set(relative, exports);
  const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.React, esModuleInterop: true } }).outputText;
  const require = name => {
    if (name === 'react') return React;
    if (name === 'react-native-svg') return Object.fromEntries(['Circle', 'Ellipse', 'G', 'Line', 'Path', 'Polygon', 'Rect'].map(tag => [tag, tag.toLowerCase()]));
    const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(relative), name));
    for (const suffix of ['.ts', '.tsx', '/index.ts']) if (fs.existsSync(path.join(base, resolved + suffix))) return load(resolved + suffix);
    throw new Error(`Unexpected face import: ${name}`);
  };
  vm.runInNewContext(code, { exports, require }, { filename: relative, timeout: 1000 });
  return exports;
}
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
function svg(node) {
  if (node == null || node === false) return '';
  if (Array.isArray(node)) return node.map(svg).join('');
  if (typeof node.type === 'function') return svg(node.type(node.props));
  if (node.type === 'fragment') return svg(node.props.children);
  const attrs = Object.entries(node.props).filter(([key]) => !['children', 'testID', 'key'].includes(key)).map(([key, value]) => ` ${key.replace(/[A-Z]/g, c => '-' + c.toLowerCase())}="${escape(value)}"`).join('');
  return `<${node.type}${attrs}>${svg(node.props.children)}</${node.type}>`;
}
const layers = load('faces/face-tile.tsx');
const faces = load('faces/index.ts').FACE_IDS;
const templates = Object.fromEntries(faces.map(face => [face, {
  agent: svg(layers.agentFaceLayers(face)),
  human: svg(layers.personFaceLayers(face, '__HUE__', 'light')),
}]));
const paletteSource = fs.readFileSync(path.join(base, 'identity-mark.ts'), 'utf8');
const ast = ts.createSourceFile('identity-mark.ts', paletteSource, ts.ScriptTarget.Latest, true);
const names = new Set(['IdentityKind', 'IdentityPalette', 'fnv1a32', 'mulberry32', 'HUE_WHEEL', 'isWarmAnchor', 'WORKSPACE_BRASS_HUE', 'TEMPERAMENT', 'weightedHueIndex', 'hslToHex', 'identityPalette']);
const palette = ast.statements.filter(node => {
  const name = node.name?.text ?? node.declarationList?.declarations[0]?.name?.text;
  return names.has(name);
}).map(node => node.getText(ast).replace(/^export /, node.name?.text === 'identityPalette' ? 'export ' : '')).join('\n\n');
const outputs = {
  'apps/server/src/face-templates.generated.json': JSON.stringify(templates, null, 2) + '\n',
  'apps/server/src/face-palette.generated.ts': '// Generated by scripts/generate-server-faces.mjs from the mobile face source.\n' + palette + '\n',
};
for (const [relative, content] of Object.entries(outputs)) {
  const target = path.join(root, relative);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== content) throw new Error(`${relative} is stale; run node scripts/generate-server-faces.mjs`);
  } else fs.writeFileSync(target, content);
}
