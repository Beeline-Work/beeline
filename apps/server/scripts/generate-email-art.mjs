function expand(node) {
  if (!node || typeof node !== 'object') return node;
  if (typeof node.type === 'function') return expand(node.type(node.props));
  return { ...node, props: { ...node.props, ...(node.props.children ? { children: node.props.children.flat().map(expand) } : {}) } };
}
function svg(node) {
  if (!node || typeof node !== 'object') return '';
  const { children, ...props } = node.props;
  const attrs = Object.entries(props).filter(([,v]) => v !== undefined).map(([k,v]) => `${k.replace(/[A-Z]/g,m=>'-'+m.toLowerCase())}="${v}"`).join(' ');
  return `<${node.type} ${attrs}>${(children ?? []).map(svg).join('')}</${node.type}>`;
}
