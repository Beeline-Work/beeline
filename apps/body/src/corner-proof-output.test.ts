import { execFile } from 'node:child_process';
import { mkdtemp, writeFile, readFile, rm, access, symlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { promisify } from 'node:util';
import { afterEach, expect, it } from 'vitest';
import { declareCornerProofOutput, reclaimCornerProofOutput } from './corner-proof-output.js';
const exec = promisify(execFile);
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map(root => rm(root, { recursive: true, force: true }))); });
const exists = (path: string) => access(path).then(() => true, () => false);
it('expires only declared ignored untracked proof after archive retention, protecting source and active use', async () => {
  const root = await mkdtemp(resolve(tmpdir(), 'proof-retention-')); roots.push(root);
  await exec('git', ['init', root]);
  await writeFile(resolve(root, '.gitignore'), '.beeline-proof/\n');
  await writeFile(resolve(root, 'source.ts'), 'keep');
  const proof = await declareCornerProofOutput(root, 'corner');
  await writeFile(resolve(proof, 'screenshot.png'), 'generated');
  const now = Date.now(), old = now - 8 * 86400_000;
  await reclaimCornerProofOutput(root, 'corner', now, { now, inUse: async () => false });
  expect(await exists(proof)).toBe(true);
  await reclaimCornerProofOutput(root, 'different', old, { now, inUse: async () => false });
  expect(await exists(proof)).toBe(true);
  await reclaimCornerProofOutput(root, 'corner', old, { now, inUse: async () => true });
  expect(await exists(proof)).toBe(true);
  await exec('git', ['-C', root, 'add', '-f', '.beeline-proof/screenshot.png']);
  await reclaimCornerProofOutput(root, 'corner', old, { now, inUse: async () => false });
  expect(await exists(proof)).toBe(true);
  await exec('git', ['-C', root, 'rm', '--cached', '-f', '.beeline-proof/screenshot.png']);
  await reclaimCornerProofOutput(root, 'corner', old, { now, inUse: async () => false });
  expect(await exists(proof)).toBe(false);
  expect(await readFile(resolve(root, 'source.ts'), 'utf8')).toBe('keep');
});
it('refuses linked proof directories', async () => {
  const root = await mkdtemp(resolve(tmpdir(), 'proof-link-')); roots.push(root);
  const external = await mkdtemp(resolve(tmpdir(), 'proof-external-')); roots.push(external);
  await symlink(external, resolve(root, '.beeline-proof'));
  await expect(declareCornerProofOutput(root, 'corner')).rejects.toThrow('ordinary');
});
