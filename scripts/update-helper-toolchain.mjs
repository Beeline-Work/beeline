const start = installer.indexOf('# BEGIN GENERATED HELPER NODE');
if (start >= 0) installer = installer.slice(0, start) + block + installer.slice(installer.indexOf('# END GENERATED HELPER NODE', start) + '# END GENERATED HELPER NODE'.length);
else installer = installer.replace("command -v node >/dev/null 2>&1 || fail 'Node.js >=20.11 is required'\nnode -e 'const v=process.versions.node.split(\".\").map(Number);process.exit(v[0]>20||(v[0]===20&&v[1]>=11)?0:1)' || fail 'Node.js >=20.11 is required'", block);
await writeFile(installerPath, installer);
