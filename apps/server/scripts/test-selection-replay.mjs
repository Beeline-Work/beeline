// Replays past PRs through the PR test selector and records, per PR, what it
// would run and which really-failed test files it would have skipped.
//
//   node scripts/test-selection-replay.mjs --map MAP --prs SELECTED_PRS_JSON \
//     --failures FAILURE_HISTORY_JSON [--timings TIMINGS_JSON] [--report REPORT_JSON]
//
// SELECTED_PRS_JSON and FAILURE_HISTORY_JSON are the step 1 CI measurement
// files (PR heads and bases; per-file CI failures with a flaky/real label).
// It rewrites test-selection-replay.json, which the selection test replays.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { gitChanges, selectTests, serverTestFiles, sourceTextTests } from './test-selection.mjs';

const repo = fileURLToPath(new URL('../../../', import.meta.url));
const ts = createRequire(`${repo}package.json`)('typescript');
const argument = (name) => {
  const index = process.argv.indexOf(name);
  return index < 0 ? undefined : process.argv[index + 1];
};
const read = (path) => JSON.parse(readFileSync(path, 'utf8'));
const git = (args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim();

const map = read(argument('--map'));
const prs = read(argument('--prs'));
const failures = read(argument('--failures'));
const timings = argument('--timings') ? read(argument('--timings')) : {};
const alwaysRun = sourceTextTests(ts);
const testFiles = serverTestFiles();

const replayed = [];
const report = [];
for (const pr of prs) {
  const base = git(['merge-base', pr.baseRefOid, pr.headRefOid]);
  const changes = gitChanges(ts, base, pr.headRefOid);
  const observed = failures.filter((failure) => failure.prNumbers.includes(pr.number) && failure.classification !== 'flaky');
  const failed = [...new Set(observed.map((failure) => failure.file))].filter((file) => testFiles.includes(file)).sort();
  const absent = [...new Set(observed.map((failure) => failure.file))].filter((file) => !testFiles.includes(file)).sort();
  const selection = selectTests({ map, changes, alwaysRun, testFiles });
  const selected = selection.mode === 'full' ? testFiles : selection.files;
  const time = (files) => files.reduce((sum, file) => sum + (timings[file] ?? 0), 0);
  replayed.push({ number: pr.number, changes, failed });
  report.push({
    number: pr.number, title: pr.title, mode: selection.mode, reason: selection.reason,
    selectedFiles: selected.length, totalFiles: testFiles.length,
    selectedSeconds: time(selected) / 1000, fullSeconds: time(testFiles) / 1000,
    failed, missed: failed.filter((file) => !selected.includes(file)), failedFilesNoLongerOnMain: absent,
    selected,
  });
}

// Keep only the map entries these PRs touch, so the fixture stays small.
const touched = new Set(replayed.flatMap((pr) => pr.changes.map((change) => change.path)));
const pick = (entries) => Object.fromEntries(Object.entries(entries).filter(([path]) => touched.has(path)));
const fixture = {
  note: 'Generated by test-selection-replay.mjs from a full coverage map and step 1 CI failure history.',
  mapCommit: map.commit,
  alwaysRun,
  testFiles,
  map: { ...map, sources: pick(map.sources), reads: pick(map.reads), files: map.files.filter((path) => touched.has(path)) },
  prs: replayed,
};
writeFileSync(new URL('./test-selection-replay.json', import.meta.url), `${JSON.stringify(fixture)}\n`);

const sorted = (values) => [...values].sort((a, b) => a - b);
const quantile = (values, q) => sorted(values)[Math.max(0, Math.ceil(q * values.length) - 1)];
const saved = report.map((row) => 1 - row.selectedSeconds / row.fullSeconds);
const summary = {
  prs: report.length,
  fullFallbacks: report.filter((row) => row.mode === 'full').length,
  misses: report.reduce((sum, row) => sum + row.missed.length, 0),
  prsWithFailures: report.filter((row) => row.failed.length).length,
  medianSelectedFiles: quantile(report.map((row) => row.selectedFiles), 0.5),
  medianSelectedSeconds: quantile(report.map((row) => row.selectedSeconds), 0.5),
  p90SelectedSeconds: quantile(report.map((row) => row.selectedSeconds), 0.9),
  fullSeconds: report[0]?.fullSeconds,
  medianSaved: quantile(saved, 0.5),
  meanSaved: saved.reduce((sum, value) => sum + value, 0) / saved.length,
};
if (argument('--report')) writeFileSync(argument('--report'), JSON.stringify({ summary, prs: report }, null, 2));
console.log(JSON.stringify(summary, null, 2));
for (const row of report) {
  console.log(`#${row.number} ${row.mode} ${row.selectedFiles}/${row.totalFiles} files, ${row.selectedSeconds.toFixed(0)}s`
    + `${row.failed.length ? `, failed ${row.failed.length}, missed ${row.missed.length}` : ''}${row.mode === 'full' ? ` (${row.reason})` : ''}`);
}
if (summary.misses) process.exitCode = 1;
