// Maintainer-only: edit pins/URLs in the manifest, then regenerate verified bytes.
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
const manifestPath = 'apps/body/src/helper-toolchain-manifest.ts';
const source = await readFile(manifestPath, 'utf8');
const seed = JSON.parse(source.split('export const HELPER_TOOLCHAIN_MANIFEST = ')[1].trim().replace(/;$/, ''));
const root = await mkdtemp(join(tmpdir(), 'beeline-toolchain-pins-'));
const platforms = seed.platforms;
async function get(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(180_000) });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response;
}
const hashes = new Map();
const integrities = new Map();
async function hash(url) {
  if (!hashes.has(url)) hashes.set(url, (async () => {
    const digest = createHash('sha256');
    const sri = createHash('sha512');
    for await (const chunk of (await get(url)).body) { digest.update(chunk); sri.update(chunk); }
    integrities.set(url, 'sha512-' + sri.digest('base64'));
    return digest.digest('hex');
  })());
  return hashes.get(url);
}
const manifest = { platforms, node: { version: seed.node.version, platforms: {} }, npm: {}, native: seed.native };
const sums = await (await get(`https://nodejs.org/dist/v${seed.node.version}/SHASUMS256.txt`)).text();
for (const platform of platforms) {
  const file = `node-v${seed.node.version}-${platform}.tar.gz`;
  manifest.node.platforms[platform] = { url: `https://nodejs.org/dist/v${seed.node.version}/${file}`, sha256: sums.split('\n').find(line => line.endsWith(`  ${file}`)).split(' ')[0] };
}
const jobs = [];
try {
  for (const [kind, previous] of Object.entries(seed.npm)) {
    const dir = join(root, kind);
    await mkdir(dir, { recursive: true });
    const pkg = previous.package;
    await writeFile(join(dir, 'package.json'), JSON.stringify(pkg));
    await writeFile(join(dir, 'package-lock.json'), JSON.stringify(previous.lock));
    execFileSync('npm', ['install', '--package-lock-only', '--ignore-scripts', '--no-audit', '--no-fund', '--prefix', dir], { stdio: 'inherit' });
    const lock = JSON.parse(await readFile(join(dir, 'package-lock.json'), 'utf8'));
    const artifacts = {};
    for (const [path, entry] of Object.entries(lock.packages)) {
      if (!path || !entry.resolved) continue;
      const targets = platforms.filter(p => {
        const [os, cpu] = p.split('-');
        return (!entry.os || entry.os.includes(os)) && (!entry.cpu || entry.cpu.includes(cpu));
      });
      if (!targets.length) continue;
      jobs.push(async () => {
        artifacts[path] = { version: entry.version, url: entry.resolved, sha256: await hash(entry.resolved), platforms: targets };
        const integrity = integrities.get(entry.resolved);
        if (entry.integrity && entry.integrity !== integrity) throw new Error(`Registry integrity mismatch: ${entry.resolved}`);
        entry.integrity = integrity;
      });
    }
    manifest.npm[kind] = { package: pkg, lock, artifacts };
  }
  for (const dependency of Object.values(manifest.native)) {
    for (const spec of Object.values(dependency.platforms)) {
      jobs.push(async () => { spec.sha256 = await hash(spec.url); spec.version = dependency.version; });
    }
  }
  let completed = 0;
  await Promise.all(Array.from({ length: 4 }, async () => {
    for (;;) {
      const job = jobs.shift();
      if (!job) break;
      await job();
      if (++completed % 25 === 0) console.log(`Hashed ${completed} artifacts`);
    }
  }));
  await writeFile(manifestPath, `// Generated by scripts/update-helper-toolchain.mjs. Review pins, locks and SHA-256 together.\nexport const HELPER_TOOLCHAIN_MANIFEST = ${JSON.stringify(sorted(manifest), null, 2)};\n`);
  console.log(`Wrote manifest with ${completed} verified artifacts`);
} finally { await rm(root, { recursive: true, force: true }); }
// Stable ordering keeps pin diffs reviewable despite concurrent downloads.
function sorted(value) {
  if (Array.isArray(value)) return value.map(sorted);
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map(k => [k, sorted(value[k])]));
  return value;
}
const installerPath = 'relay-stack/web/install.sh';
let installer = await readFile(installerPath, 'utf8');
const cases = platforms.map(platform => {
  const spec = manifest.node.platforms[platform];
  const generation = createHash('sha256').update(JSON.stringify(sorted(spec))).digest('hex').slice(0, 16);
  return `  ${platform}) node_url='${spec.url}'; node_sha='${spec.sha256}'; node_generation='node-${manifest.node.version}-${generation}' ;;`;
}).join('\n');
