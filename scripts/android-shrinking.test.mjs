import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
const require = createRequire(import.meta.url);
const plugin = require('../apps/mobile/plugins/withAndroidBuildTooling.js');

test('prebuild mods enable release optimization without changing debug and preserve keep rules on rerun', async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'beeline-r8-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  await fs.mkdir(path.join(root, 'app'), { recursive: true });
  await fs.writeFile(path.join(root, 'app/proguard-rules.pro'), '# Existing rules\n');
  const config = plugin({ name: 'test', slug: 'test' });
  const request = { platformProjectRoot: root, platform: 'android' };
  const properties = await config.mods.android.gradleProperties({ modRequest: request, modResults: [] });
  const values = Object.fromEntries(properties.modResults.map(p => [p.key, p.value]));
  assert.equal(values['android.enableMinifyInReleaseBuilds'], 'true');
  assert.equal(values['android.enableShrinkResourcesInReleaseBuilds'], 'true');
  const template = execFileSync('tar', ['-xOf', 'apps/mobile/node_modules/expo/template.tgz', 'package/android/app/build.gradle'], { encoding: 'utf8' });
  const result = await config.mods.android.appBuildGradle({ modRequest: request, modResults: { language: 'groovy', contents: template } });
  const contents = result.modResults.contents;
  assert.match(contents, /minifyEnabled enableMinifyInReleaseBuilds/);
  assert.match(contents, /shrinkResources enableShrinkResources.toBoolean\(\)/);
  assert.match(contents, /proguard-android-optimize.txt/);
  assert.equal(contents.match(/buildTypes \{\s*debug \{[^}]+\}/)[0], template.match(/buildTypes \{\s*debug \{[^}]+\}/)[0]);
  await config.mods.android.dangerous({ modRequest: request });
  const first = await fs.readFile(path.join(root, 'app/proguard-rules.pro'), 'utf8');
  await config.mods.android.dangerous({ modRequest: request });
  assert.equal(await fs.readFile(path.join(root, 'app/proguard-rules.pro'), 'utf8'), first);
  await fs.appendFile(path.join(root, 'app/proguard-rules.pro'), '# Later plugin rules\n');
  await config.mods.android.dangerous({ modRequest: request });
  assert.match(await fs.readFile(path.join(root, 'app/proguard-rules.pro'), 'utf8'), /# Later plugin rules/);
  assert.match(first, /# Existing rules/);
  assert.match(first, /livekit.org.webrtc/);
  assert.match(first, /-keep class livekit\.org\.jni_zero\.\*\*/);
  assert.match(first, /-keep @interface expo\.modules\.kotlin\.records\.Field/);
  assert.match(first, /app.usebeeline.crashtrace/);
  assert.match(await fs.readFile(path.join(root, 'app/src/main/res/raw/beeline_keep.xml'), 'utf8'), /notification_icon/);
});
