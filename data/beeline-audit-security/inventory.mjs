import ts from 'typescript';
import { readFileSync, writeFileSync } from 'node:fs';
const walk = (node, callback) => { callback(node); ts.forEachChild(node, child => walk(child, callback)); };
for (const kind of ['phone', 'daemon']) {
  const path = `apps/server/src/${kind}-service.ts`;
  const source = ts.createSourceFile(path, readFileSync(path, 'utf8'), ts.ScriptTarget.Latest, true);
  const methods = new Map();
  walk(source, node => { if (ts.isMethodDeclaration(node) && node.body) methods.set(node.name.getText(source), node); });
  const execute = methods.get('execute');
  const dispatch = execute.body.statements.find(node => ts.isSwitchStatement(node) && node.expression.getText(source) === 'name');
  const calls = node => {
    const names = new Set();
    walk(node, child => { if (ts.isCallExpression(child)) names.add(child.expression.getText(source).replace(/\s+/g, ' ').replace(/\|/g, '\\|')); });
    return [...names];
  };
  const location = node => `${path}:${source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1}`;
  const guard = /(?:access|reach|require|authoriz|owner|member|permission|grant|assert|humanRoom|Readable|mayView|computerView|handBackComputer|endComputer)/i;
  const expand = (names, seen = new Set()) => {
    const result = new Set();
    for (const name of names) {
      if (/^(?:this\.)?[A-Za-z0-9_.]+$/.test(name) && guard.test(name)) result.add(name);
      if (!name.startsWith('this.')) continue;
      const key = name.slice(5), method = methods.get(key);
      if (!method || seen.has(key)) continue;
      seen.add(key);
      for (const found of expand(calls(method), seen)) result.add(found);
    }
    return result;
  };
  const rows = [];
  for (let i = 0; i < dispatch.caseBlock.clauses.length; i++) {
    const clause = dispatch.caseBlock.clauses[i];
    if (!ts.isCaseClause(clause)) continue;
    let body = clause, j = i;
    while (!body.statements.length && j + 1 < dispatch.caseBlock.clauses.length) body = dispatch.caseBlock.clauses[++j];
    const direct = calls(body);
    rows.push(`| ${clause.expression.text} | ${location(clause)} | ${direct.filter(name => name.startsWith('this.') || /^[A-Za-z]+$/.test(name)).join(', ')} | ${[...expand(direct)].join(', ') || 'inline SQL / identity-scoped; inspect body'} |`);
  }
  if (kind === 'phone') for (const name of ['openComputerSession', 'handbackComputerSession', 'endComputerSession']) {
    rows.unshift(`| ${name} | ${location(execute)} | pre-switch computer-session handler | viewer-bound helper |`);
  }
  writeFileSync(`data/beeline-audit-security/${kind}-operations.md`, `# ${kind} dispatch and authorization pointers\n\nGenerated by \`node data/beeline-audit-security/inventory.mjs\`. ${rows.length} operation labels. These are mechanical source pointers, not a proof that every reachable guard protects every branch. External helper policies and inline SQL must be read separately.\n\n${kind === 'daemon' ? 'Shared dispatch guard: token/candidate agent equality, current Room membership, corner-target reach, and command-generation validation for turn writes in `DaemonService.execute`.' : 'Shared transport guard: phone access bearer authenticated in `server.ts`; service resolves current viewer, spectator write policy, then operation-specific membership/owner/manager checks.'}\n\n| Operation | Dispatch | Direct calls | Reachable guard pointers |\n|---|---|---|---|\n${rows.join('\n')}\n`);
  console.log(`${kind}: ${rows.length} operations`);
}
